// Regenerates init.sql from the migrations in drizzle/, so a fresh database
// created from init.sql is identical to one built by running the migrations.
//
//   npm run db:init-sql      (run after every `npm run db:generate`)
//
// init.sql also records each migration as applied, so the app's startup
// migrator sees nothing left to do. Default data (admin user, settings) is
// seeded by the app on first start.
import fs from 'fs';
import { readMigrationFiles } from 'drizzle-orm/migrator';

const migrations = readMigrationFiles({ migrationsFolder: 'drizzle' });
const journal = JSON.parse(fs.readFileSync('drizzle/meta/_journal.json', 'utf8'));
const quote = (s) => `'${s.replace(/'/g, "''")}'`;

const out = [
  '-- Haujee Jewellery / JewelMS database schema (PostgreSQL).',
  '-- GENERATED by scripts/generate-init-sql.mjs from drizzle/. Do not edit by hand:',
  '-- change src/db/schema.ts, run `npm run db:generate`, then `npm run db:init-sql`.',
  '--',
  '-- Used to create a fresh database (docker-entrypoint-initdb.d). The admin user',
  '-- and default settings are created by the app on its first start.',
  '',
  'BEGIN;',
  '',
];

migrations.forEach((m, i) => {
  out.push(`-- Migration ${journal.entries[i].tag}`);
  for (const statement of m.sql) out.push(statement.trim().replace(/;?$/, ';'));
  out.push('');
});

out.push(
  '-- Record the migrations above as applied.',
  'CREATE SCHEMA IF NOT EXISTS drizzle;',
  'CREATE TABLE IF NOT EXISTS drizzle.__drizzle_migrations (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint);',
  ...migrations.map(m => `INSERT INTO drizzle.__drizzle_migrations (hash, created_at) VALUES (${quote(m.hash)}, ${m.folderMillis});`),
  '',
  'COMMIT;',
  '',
);

fs.writeFileSync('init.sql', out.join('\n'));
console.log(`init.sql written from ${migrations.length} migration(s).`);
